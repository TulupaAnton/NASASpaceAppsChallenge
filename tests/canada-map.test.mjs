import assert from 'node:assert/strict';
import fs from 'node:fs';
import test from 'node:test';
import vm from 'node:vm';
import { CANADA_REGIONS, CANADA_SITES, canadaSelection, getCountry, matchingCountries } from '../app/lib/countries.js';
import { createMapProjection } from '../app/lib/map-projections.js';
import { collectRegions, findRegion } from '../public/legacy/projection.js';

const root = new URL('../', import.meta.url);
const geometry = JSON.parse(fs.readFileSync(new URL('public/countries/ca/geometry.json', root)));
const regions = collectRegions(geometry.regionData);
const projection = createMapProjection(geometry.projection);

test('Canada has all 13 units, including Arctic islands, and excludes neighboring countries and water', () => {
  assert.equal(geometry.regionData.length, 13);
  assert.deepEqual(new Set(geometry.regionData.map(region => region.code)), new Set(Object.values(CANADA_REGIONS)));
  for (const site of CANADA_SITES) assert.equal(findRegion(regions, ...site.point), site.region, site.name);
  assert.equal(findRegion(regions, -75.7, 82.5), 'Nunavut', 'Ellesmere Island remains selectable');
  for (const point of [[-149.9, 61.2181], [-51.7, 64.18], [-81.3774, 28.5383], [-79, 43]]) {
    assert.equal(findRegion(regions, ...point), null, 'Alaska, Greenland, continental US and Lake Ontario are excluded');
  }
});

test('Canada projection agrees with independent PROJ raster control points and reverses accurately', () => {
  // Control values generated by pyproj for the raster's spherical LCC definition.
  const controls = [
    [[-123.1207, 49.2827], [363.9822017776545, 712.440702279912]],
    [[-68.517, 63.7467], [966.5603864542318, 438.87543651851456]],
    [[-96, 82], [725.601796618759, 110.78168141288569]],
    [[-102, 56], [656.4309009904688, 647.4627940191053]],
  ];
  for (const [point, expected] of controls) {
    projection.project(...point).forEach((value, index) => assert.ok(Math.abs(value - expected[index]) < 1e-8));
  }
  for (const site of CANADA_SITES) {
    const xy = projection.project(...site.point);
    assert.ok(xy[0] > 0 && xy[0] < projection.width && xy[1] > 0 && xy[1] < projection.height);
    projection.unproject(...xy).forEach((value, index) => assert.ok(Math.abs(value - site.point[index]) < 1e-9));
  }
  const finnish = createMapProjection();
  const point = [24.9384, 60.1699];
  finnish.unproject(...finnish.project(...point)).forEach((value, index) => assert.ok(Math.abs(value - point[index]) < 1e-8));
});

test('country search and Canadian handoff preserve identity without a Finnish reference ID', () => {
  assert.deepEqual(matchingCountries(' ca ').map(country => country.code), ['CA']);
  assert.deepEqual(matchingCountries('F').map(country => country.code), ['FI']);
  assert.equal(matchingCountries('').length, 2);
  assert.equal(matchingCountries('Canada!').length, 0);
  assert.throws(() => getCountry('US'), RangeError);
  const city = CANADA_SITES.find(site => site.name === 'Calgary');
  const chosen = canadaSelection(city.point, city.region, city);
  assert.equal(chosen.countryCode, 'CA');
  assert.equal(chosen.regionCode, 'CA-AB');
  assert.equal(chosen.markerId, 'ca_calgary');
  assert.equal(chosen.referenceSiteId, null);
  assert.equal(chosen.siteId, undefined);
  const arbitrary = canadaSelection([-100, 50], 'Manitoba');
  assert.equal(arbitrary.markerId, null);
  assert.equal(arbitrary.regionCode, 'CA-MB');
  assert.equal(arbitrary.index, undefined);
});

function canvasContext(onTranslate = () => {}) {
  const methods = {
    translate: onTranslate,
    scale(k) { methods.k = k; },
    measureText: text => ({ width: text.length * 6 }),
    createLinearGradient: () => ({ addColorStop() {} }),
  };
  return new Proxy(methods, { get: (target, key) => target[key] ?? (() => {}) });
}

async function preparedCanada() {
  const context = {
    getCountry, canadaSelection, createMapProjection, collectRegions, findRegion,
    finlandSites: [], selection() { throw new Error('Canada must not construct a Finnish selection'); },
    loadFinlandGeometry() { throw new Error('Canada must not load Finnish geometry'); },
    Image: class { async decode() {} },
    Path2D: class { moveTo() {} lineTo() {} closePath() {} addPath() {} },
    document: { createElement: () => ({ getContext: () => canvasContext() }) },
    fetch: async url => { assert.equal(url, getCountry('CA').geometry); return { ok: true, json: async () => geometry }; },
  };
  const source = ['app/lib/map-artwork.js', 'app/lib/map-assets.js'].map(file =>
    fs.readFileSync(new URL(file, root), 'utf8').replace(/^import .*;\n/gm, '').replace(/\bexport /g, '')
      .replaceAll('import.meta.url', "'http://localhost/map-assets.js'")).join('\n');
  vm.createContext(context);
  vm.runInContext(source + '\nglobalThis.loadMap=loadMap;', context);
  const first = context.loadMap('CA');
  assert.equal(first, context.loadMap('CA'), 'map loading is deduplicated per country');
  const assets = await first;
  for (const site of CANADA_SITES) assert.equal(assets.regionAt(...site.point), site.region);
  return assets;
}

test('Canadian canvas picking survives zoom and pan while marking keeps the full-country framing', async () => {
  const assets = await preparedCanada();
  let pose = {}, queue = new Map(), id = 0, now = 0, missed = 0;
  const handlers = {}, chosen = [];
  const ctx = canvasContext((x, y) => { pose = { x, y }; });
  const canvas = { style: {}, getContext: () => ctx, getBoundingClientRect: () => ({ width: 1600, height: 900, left: 0, top: 0 }),
    addEventListener: (name, fn) => { handlers[name] = fn; }, removeEventListener() {}, setPointerCapture() {} };
  const context = {
    IMAGE_WIDTH: 1280, IMAGE_HEIGHT: 720, sites: [], comparisonColors: [],
    selection() { throw new Error('A Canadian map must use its own selection constructor'); },
    unproject() { throw new Error('A Canadian click must use the Canadian projection'); },
    window: { devicePixelRatio: 1 }, performance: { now: () => now },
    ResizeObserver: class { observe() {} disconnect() {} },
    requestAnimationFrame: fn => { queue.set(++id, fn); return id; }, cancelAnimationFrame: key => queue.delete(key),
  };
  const source = fs.readFileSync(new URL('app/lib/map-view.js', root), 'utf8')
    .replace(/^import .*;\n/gm, '').replace('export function createMapView', 'function createMapView');
  vm.createContext(context);
  vm.runInContext(source + '\nglobalThis.createMapView=createMapView;', context);
  const view = context.createMapView(canvas, {}, assets, site => chosen.push(site), () => missed++, () => true);
  function frame() { now += 16; const callbacks = [...queue.values()]; queue.clear(); callbacks.forEach(fn => fn(now)); pose.k = ctx.k; }
  function pointEvent(type, x, y) { handlers[type]({ type, button: 0, pointerId: 1, pointerType: 'mouse', clientX: x, clientY: y }); }
  function click(point) {
    const xy = projection.project(...point), x = pose.x + xy[0] * pose.k, y = pose.y + xy[1] * pose.k;
    pointEvent('pointerdown', x, y); pointEvent('pointerup', x, y); frame();
  }
  view.prepareReveal(); frame();
  await view.whenPainted();
  view.finishReveal(); frame();
  click([-114.0719, 51.0447]);
  assert.equal(chosen.at(-1).name, 'Calgary');
  assert.equal(chosen.at(-1).countryCode, 'CA');
  const before = { ...pose };
  view.mark(chosen.at(-1)); frame();
  assert.deepEqual(pose, before, 'a pin must not isolate or resize Canada');
  view.zoom(1.4); frame();
  pointEvent('pointerdown', 800, 450); pointEvent('pointermove', 850, 475); pointEvent('pointerup', 850, 475); frame();
  click([-100, 50]);
  assert.equal(chosen.at(-1).regionCode, 'CA-MB');
  assert.ok(Math.abs(chosen.at(-1).latitude - 50) < 1e-9);
  assert.equal(chosen.at(-1).markerId, null);
  view.zoom(1); frame();
  click([-79, 43]);
  assert.equal(missed, 1, 'a click in Lake Ontario must not open analysis');
  assert.equal(chosen.length, 2);
  view.destroy();
});
